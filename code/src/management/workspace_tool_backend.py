"""Provider-neutral file tools for a staged memory workspace."""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path
from typing import Any

from ..markdown.syntax import definition_match


class WorkspaceToolError(ValueError):
    """A model tool request violated the staged-workspace contract."""

    def __init__(self, message: str, *, recovery: dict[str, Any] | None = None):
        super().__init__(message)
        self.recovery = recovery


class WorkspaceToolBackend:
    """Constrained file operations shared by every agent adapter."""

    def __init__(self, root: str | Path, *, max_output_chars: int | None = None,
                 unchecked: bool = False) -> None:
        self.root = Path(root).resolve()
        if max_output_chars is not None and max_output_chars < 1024:
            raise ValueError("max_output_chars must be at least 1024")
        self._needs_read: set[Path] = set()
        self.max_output_chars = max_output_chars
        self.unchecked = unchecked
        if not self.root.is_dir():
            raise ValueError(f"workspace does not exist: {self.root}")

    def _path(self, raw: str, *, writable: bool = False) -> Path:
        value = str(raw).strip()
        if not value or Path(value).is_absolute():
            raise WorkspaceToolError("path must be non-empty and relative")
        path = (self.root / value).resolve()
        try:
            relative = path.relative_to(self.root).as_posix()
        except ValueError as exc:
            raise WorkspaceToolError("path escapes the workspace") from exc
        if writable and not (
            relative == "core.md" or relative.startswith("topics/")
        ):
            raise WorkspaceToolError(
                "writes are allowed only in core.md and topics/. Timeline and other "
                "derived views are generated by Runtime from Topics; do not write or "
                "retry writing them. Keep supported facts and evidence in Topics. "
                "Sources are read-only evidence.",
                recovery={"applied": False, "reason": "forbidden_write",
                          "retryable": False, "path": relative},
            )
        return path

    def _rejected_edit(self, target: Path, message: str, **details: Any) -> WorkspaceToolError:
        self._needs_read.add(target)
        path = target.relative_to(self.root).as_posix()
        return WorkspaceToolError(
            message + f". This call changed nothing. Read the CURRENT STAGED file {path} before retrying; "
            "ReadCommitted is the older committed version and does not satisfy this requirement. "
            "use its current text, not the proposed replacement from this failed call.",
            recovery={"applied": False, "path": path, "requires_read": True,
                      "next_tool": "Read", "read_arguments": {"path": path},
                      "read_version": "current_staged", **details},
        )

    def _require_read(self, target: Path) -> None:
        if target in self._needs_read:
            raise self._rejected_edit(target, "previous mutation failed; a fresh Read is required")

    def read(self, path: str, *, char_offset: int = 0,
             char_limit: int | None = None) -> dict[str, Any]:
        target = self._path(path)
        if not target.is_file():
            raise WorkspaceToolError(f"file not found: {path}")
        text = target.read_text(encoding="utf-8")
        if self.max_output_chars is None and char_limit is None and char_offset == 0 and path != "repair-diagnostics.json":
            self._needs_read.discard(target)
            return {"path": path, "content": text}
        if char_offset < 0 or char_offset > len(text):
            raise WorkspaceToolError("char_offset is outside the file")
        if char_limit is not None and char_limit < 1:
            raise WorkspaceToolError("char_limit must be positive")
        cap = self.max_output_chars or 12000
        limit = min(char_limit or cap, cap)
        end = min(len(text), char_offset + limit)
        self._needs_read.discard(target)
        return {
            "path": path, "content": text[char_offset:end],
            "char_offset": char_offset, "total_chars": len(text),
            "next_char_offset": end if end < len(text) else None,
            "truncated": end < len(text),
        }

    def write(self, path: str, content: str) -> dict[str, Any]:
        target = self._path(path, writable=True)
        self._require_read(target)
        if not self.unchecked:
            self._guard_block_ids(target, str(content))
            self._guard_footnotes(target, str(content))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(str(content), encoding="utf-8")
        return {"path": path, "bytes": len(str(content).encode("utf-8"))}

    def _guard_block_ids(self, target: Path, updated: str) -> None:
        """Reject a single tool call that would orphan an existing memory ID."""
        if not target.is_file():
            return
        ids = set(re.findall(r"(?<!\S)\^([0-9a-f]{8})(?=\s|$)",
                             target.read_text(encoding="utf-8"), re.MULTILINE))
        if not ids:
            return
        retained = set(re.findall(r"(?<!\S)\^([0-9a-f]{8})(?=\s|$)",
                                  updated, re.MULTILINE))
        missing = ids - retained
        if missing:
            for other in [self.root / "core.md", *(self.root / "topics").rglob("*.md")]:
                if not other.is_file() or other.resolve() == target:
                    continue
                missing -= set(re.findall(r"(?<!\S)\^([0-9a-f]{8})(?=\s|$)",
                                          other.read_text(encoding="utf-8"), re.MULTILINE))
                if not missing:
                    break
        if missing:
            raise self._rejected_edit(target,
                "edit would remove existing memory block ID(s): "
                + ", ".join(sorted(missing))
                + ". Preserve each ID on its original fact, or move the fact "
                "with the same ID to its destination before replacing this file. "
                "Read the current file and use Edit for local changes."
            )

    def _guard_footnotes(self, target: Path, updated: str) -> None:
        """Reject newly broken existing citations before changing staged bytes.

        Local labels remain legal while the Writer appends their definitions.
        Existing invalid candidates may still be repaired incrementally.
        """
        original = target.read_text(encoding="utf-8") if target.is_file() else ""
        def definitions(text):
            result: dict[str, list[str]] = {}
            for line in text.splitlines():
                match = definition_match(line)
                if match:
                    result.setdefault(match.group('id'), []).append(line)
            return result
        before, after = definitions(original), definitions(updated)
        duplicates = [label for label, lines in after.items()
                      if re.fullmatch(r'e-[0-9a-f]{10}', label) and len(lines) > 1
                      and (len(lines) > len(before.get(label, []))
                           or not set(lines).issubset(before.get(label, [])))]
        if duplicates:
            raise self._rejected_edit(target,
                "mutation introduces duplicate stable footnote definition(s): "
                + ', '.join(sorted(duplicates))
                + ". An existing evidence ID cannot be reused for a different date or source. "
                "Keep the original definition and citations. For a new fact, use a fresh "
                "file-local label and its own verified definition; Runtime assigns its stable ID. "
                "Do not delete old evidence to make room for the new definition.",
                reason='duplicate_stable_footnote',
                existing_definitions={label: before.get(label, []) for label in duplicates[:8]})
        prose = '\n'.join(line for line in updated.splitlines()
                          if not re.match(r'^\s*\[\^[^\]]+\]:', line))
        cited = set(re.findall(r'\[\^([A-Za-z0-9_-]+)\]', prose))
        missing = (set(before) - set(after)) & cited
        if missing:
            raise self._rejected_edit(target,
                "mutation removes footnote definitions still cited in this file: "
                + ', '.join(sorted(missing))
                + ". Keep those original definitions as separate lines, or update their "
                "uses and definitions together in one atomic Edit. Moving prose to another "
                "file requires its definitions there too; retain definitions here while "
                "any remaining paragraph cites them. Do not rename or guess evidence.",
                reason='referenced_definition_removal',
                required_definitions={label: before[label] for label in sorted(missing)[:8]})

    @staticmethod
    def _current_block_anchors(text: str, requested: str) -> list[dict[str, str]]:
        """Offer exact current paragraphs only when a requested block ID matches."""
        ids = set(re.findall(r'(?<!\S)\^([0-9a-f]{8})(?=\s|$)', requested))
        found = []
        for paragraph in text.split('\n\n'):
            matches = ids & set(re.findall(r'(?<!\S)\^([0-9a-f]{8})(?=\s|$)', paragraph))
            if matches and len(paragraph) <= 4000 and text.count(paragraph) == 1:
                found.append({'block_ids': ', '.join(sorted(matches)), 'current_text': paragraph})
                if len(found) == 2:
                    break
        return found

    def edit(
        self,
        path: str,
        old_string: str,
        new_string: str,
        replace_all: bool = False,
    ) -> dict[str, Any]:
        target = self._path(path, writable=True)
        if not target.is_file():
            raise WorkspaceToolError(f"file not found: {path}")
        self._require_read(target)
        old = str(old_string)
        if not old:
            raise self._rejected_edit(target, "old_string must not be empty; it does not insert text")
        text = target.read_text(encoding="utf-8")
        if not old.strip():
            # A blank separator cannot identify the intended insertion site.
            # Offer only a verified literal suffix, never perform the insertion.
            anchor = None
            lines = text.splitlines(keepends=True)
            suffix = ""
            for line in reversed(lines):
                suffix = line + suffix
                if len(suffix) > 4000:
                    break
                if suffix.strip() and text.count(suffix) == 1:
                    anchor = suffix
                    break
            guidance = (
                "old_string contains only whitespace or newlines; it cannot identify "
                "an insertion location. Do not retry a blank old_string or use "
                "replace_all to append a fact. Read the file and copy a unique "
                "non-blank passage exactly. To append, set new_string to that same "
                "passage followed by a blank line and the new paragraph/definition; "
                "retain all existing IDs and citations."
            )
            details = {"reason": "whitespace_only_anchor"}
            if anchor is not None:
                guidance += " For end-of-file insertion, this exact current suffix is unique: " + json.dumps(anchor)
                details["suggested_append_old_string"] = anchor
            raise self._rejected_edit(target, guidance, **details)
        occurrences = text.count(old)
        if occurrences == 0:
            if self.unchecked:
                return {"path": path, "replacements": 0,
                        "skipped": "missing_anchor"}
            anchors = self._current_block_anchors(text, old)
            message = "old_string was not found"
            read_arguments = {"path": path}
            if anchors:
                message += ". Exact CURRENT paragraphs with the requested block IDs: " + json.dumps(anchors)
                offset = text.find(anchors[0]["current_text"])
                read_arguments = {"path": path, "char_offset": max(0, offset - 256)}
                message += (". Read the CURRENT STAGED file at the supplied char_offset, "
                            "then copy an exact local anchor; preserve the IDs and evidence")
            raise self._rejected_edit(target, message, occurrences=0,
                                      current_block_anchors=anchors,
                                      read_arguments=read_arguments)
        if occurrences > 1 and not replace_all:
            if self.unchecked:
                return {"path": path, "replacements": 0,
                        "skipped": "ambiguous_anchor"}
            lines = [text.count("\n", 0, match.start()) + 1
                     for match in re.finditer(re.escape(old), text)][:8]
            raise self._rejected_edit(
                target, "old_string is not unique; select one occurrence with more surrounding text; "
                "use replace_all only when every occurrence should change",
                occurrences=occurrences, matching_lines=lines,
            )
        updated = text.replace(old, str(new_string), -1 if replace_all else 1)
        if updated == text:
            raise self._rejected_edit(target, "replacement is identical to current text")
        if not self.unchecked:
            self._guard_block_ids(target, updated)
            self._guard_footnotes(target, updated)
        target.write_text(updated, encoding="utf-8")
        return {"path": path, "replacements": occurrences if replace_all else 1}

    def glob(self, pattern: str) -> dict[str, Any]:
        normalized = str(pattern).strip()
        if not normalized or Path(normalized).is_absolute() or ".." in Path(normalized).parts:
            raise WorkspaceToolError("glob pattern must be relative")
        paths = [
            path.relative_to(self.root).as_posix()
            for path in self.root.glob(normalized)
            if path.is_file() and path.resolve().is_relative_to(self.root)
        ]
        return {"pattern": normalized, "paths": sorted(paths)}

    def grep(self, query: str, glob: str = "**/*", *,
             match_offset: int = 0) -> dict[str, Any]:
        try:
            expression = re.compile(str(query))
        except re.error as exc:
            raise WorkspaceToolError(f"invalid regular expression: {exc}") from exc
        if match_offset < 0:
            raise WorkspaceToolError("match_offset must be nonnegative")
        matches: list[dict[str, Any]] = []
        seen = 0
        output_chars = 0
        for relative in self.glob(glob)["paths"]:
            target = self._path(relative)
            try:
                text = target.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
            char_offset = 0
            # Offsets address the same decoded string returned by Read.
            lines = text.splitlines(keepends=True)
            for number, raw_line in enumerate(lines, start=1):
                line = raw_line.rstrip("\r\n")
                match = expression.search(line)
                if match:
                    seen += 1
                    if self.max_output_chars is None:
                        matches.append({"path": relative, "line": number, "text": line})
                    elif seen > match_offset:
                        excerpt_start = max(0, match.start() - 160)
                        item = {"path": relative, "line": number,
                                "text": line[excerpt_start:excerpt_start + 500],
                                "char_offset": char_offset + excerpt_start,
                                "line_chars": len(line), "truncated": len(line) > 500}
                        size = len(json.dumps(item, ensure_ascii=False))
                        if output_chars + size > self.max_output_chars and matches:
                            return {"query": query, "matches": matches,
                                    "next_match_offset": seen - 1, "truncated": True}
                        matches.append(item)
                        output_chars += size
                char_offset += len(raw_line)
        result = {"query": query, "matches": matches}
        if self.max_output_chars is not None:
            result.update({"next_match_offset": None, "truncated": False})
        return result

    def move(self, source: str, destination: str) -> dict[str, Any]:
        source_path = self._path(source, writable=True)
        destination_path = self._path(destination, writable=True)
        if not source_path.exists():
            raise WorkspaceToolError(f"path not found: {source}")
        if destination_path.exists():
            raise WorkspaceToolError(f"destination already exists: {destination}")
        destination_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(source_path), str(destination_path))
        return {"source": source, "destination": destination}

    def remove(self, path: str) -> dict[str, Any]:
        target = self._path(path, writable=True)
        if not target.exists():
            raise WorkspaceToolError(f"path not found: {path}")
        if not self.unchecked:
            if target.is_dir():
                for item in target.rglob("*.md"):
                    self._guard_block_ids(item, "")
            else:
                self._guard_block_ids(target, "")
        if target.is_dir():
            shutil.rmtree(target)
        else:
            target.unlink()
        return {"path": path, "removed": True}
